create or replace function public.confirm_gameweek_results(
    p_gameweek_id bigint, p_results jsonb, p_player_updates jsonb
)
returns jsonb
language plpgsql
security definer
set search_path = pg_catalog
as $$
declare
    v_gw_number integer;
    v_gw_chapter text;
    v_gameweek_status text;
    v_match_count integer;
    v_result_count integer;
    v_player_count integer;
    v_expected_player_count integer;
    v_history_count integer;
begin
    if jsonb_typeof(p_results) is distinct from 'array'
       or jsonb_typeof(p_player_updates) is distinct from 'array' then
        raise exception 'INVALID_CONFIRMATION_PAYLOAD';
    end if;

    if exists (
        select 1 from jsonb_array_elements(p_results) with ordinality as e(elem, ord)
        where case when jsonb_typeof(e.elem) is distinct from 'object' then true
                   when not (e.elem ? 'match_id' and e.elem ? 'points_a' and e.elem ? 'points_b' and e.elem ? 'winner_id' and e.elem ? 'winner_method') then true
                   when jsonb_typeof(e.elem->'match_id') is distinct from 'number' then true
                   when (e.elem->>'match_id')::numeric is distinct from trunc((e.elem->>'match_id')::numeric) then true
                   when (e.elem->>'match_id')::numeric <= 0 then true
                   when (e.elem->>'match_id')::numeric > 9223372036854775807::numeric then true
                   when jsonb_typeof(e.elem->'points_a') is distinct from 'number' then true
                   when (e.elem->>'points_a')::numeric is distinct from trunc((e.elem->>'points_a')::numeric) then true
                   when (e.elem->>'points_a')::numeric < 0 then true
                   when (e.elem->>'points_a')::numeric > 2147483647::numeric then true
                   when jsonb_typeof(e.elem->'points_b') is distinct from 'number' then true
                   when (e.elem->>'points_b')::numeric is distinct from trunc((e.elem->>'points_b')::numeric) then true
                   when (e.elem->>'points_b')::numeric < 0 then true
                   when (e.elem->>'points_b')::numeric > 2147483647::numeric then true
                   when jsonb_typeof(e.elem->'winner_id') is distinct from 'number' then true
                   when (e.elem->>'winner_id')::numeric is distinct from trunc((e.elem->>'winner_id')::numeric) then true
                   when (e.elem->>'winner_id')::numeric <= 0 then true
                   when (e.elem->>'winner_id')::numeric > 9223372036854775807::numeric then true
                   when jsonb_typeof(e.elem->'winner_method') is distinct from 'string' then true
                   when e.elem->>'winner_method' is null then true
                   when e.elem ? 'tiebreak' and nullif(e.elem->'tiebreak', 'null'::jsonb) is not null
                        and jsonb_typeof(e.elem->'tiebreak') is distinct from 'object' then true
                   else false end
    ) then
        raise exception 'INVALID_MATCH_RESULT_PAYLOAD';
    end if;

    if exists (
        select 1 from jsonb_array_elements(p_player_updates) with ordinality as e(elem, ord)
        where case when jsonb_typeof(e.elem) is distinct from 'object' then true
                   when not (e.elem ? 'player_id' and e.elem ? 'status' and e.elem ? 'hearts' and e.elem ? 'is_infected' and e.elem ? 'is_active' and e.elem ? 'before') then true
                   when jsonb_typeof(e.elem->'player_id') is distinct from 'number' then true
                   when (e.elem->>'player_id')::numeric is distinct from trunc((e.elem->>'player_id')::numeric) then true
                   when (e.elem->>'player_id')::numeric <= 0 then true
                   when (e.elem->>'player_id')::numeric > 9223372036854775807::numeric then true
                   when jsonb_typeof(e.elem->'status') is distinct from 'string' then true
                   when (e.elem->>'status') not in ('SAFE','NORMAL','DANGER') then true
                   when jsonb_typeof(e.elem->'hearts') is distinct from 'number' then true
                   when (e.elem->>'hearts')::numeric is distinct from trunc((e.elem->>'hearts')::numeric) then true
                   when (e.elem->>'hearts')::numeric < 0 then true
                   when (e.elem->>'hearts')::numeric > 3 then true
                   when jsonb_typeof(e.elem->'is_infected') is distinct from 'boolean' then true
                   when jsonb_typeof(e.elem->'is_active') is distinct from 'boolean' then true
                   when jsonb_typeof(e.elem->'before') is distinct from 'object' then true
                   when not (e.elem->'before' ? 'status' and e.elem->'before' ? 'hearts' and e.elem->'before' ? 'is_infected' and e.elem->'before' ? 'is_active') then true
                   when jsonb_typeof((e.elem->'before')->'status') is distinct from 'string' then true
                   when ((e.elem->'before')->>'status') not in ('SAFE','NORMAL','DANGER','ELIMINATED') then true
                   when jsonb_typeof((e.elem->'before')->'hearts') is distinct from 'number' then true
                   when ((e.elem->'before')->>'hearts')::numeric is distinct from trunc(((e.elem->'before')->>'hearts')::numeric) then true
                   when ((e.elem->'before')->>'hearts')::numeric < 0 then true
                   when ((e.elem->'before')->>'hearts')::numeric > 3 then true
                   when jsonb_typeof((e.elem->'before')->'is_infected') is distinct from 'boolean' then true
                   when jsonb_typeof((e.elem->'before')->'is_active') is distinct from 'boolean' then true
                   else false end
    ) then
        raise exception 'INVALID_PLAYER_UPDATE_PAYLOAD';
    end if;

    select gw_number, chapter, upper(status) into v_gw_number, v_gw_chapter, v_gameweek_status
      from public.gameweeks where id = p_gameweek_id for update;

    if not found then raise exception 'GAMEWEEK_NOT_FOUND'; end if;
    if v_gw_number is null then raise exception 'GAMEWEEK_NUMBER_REQUIRED'; end if;
    if v_gameweek_status is distinct from 'PENDING' then raise exception 'GAMEWEEK_NOT_PENDING'; end if;

    perform 1 from public.players
     where id in (select player_a_id from public.matches where gameweek_id = p_gameweek_id
                  union select player_b_id from public.matches where gameweek_id = p_gameweek_id
                  union select player_id from public.gameweek_byes where gameweek_id = p_gameweek_id)
     order by id for update;

    select count(*) into v_match_count from public.matches where gameweek_id = p_gameweek_id;
    select count(*) into v_result_count from jsonb_to_recordset(p_results) as x(match_id bigint, points_a integer, points_b integer, winner_id bigint, winner_method text, tiebreak jsonb);

    if v_match_count = 0 or v_result_count <> v_match_count then
        raise exception 'RESULT_MATCH_COUNT_MISMATCH';
    end if;

    if exists (
        select 1
          from jsonb_to_recordset(p_results) as x(match_id bigint, points_a integer, points_b integer, winner_id bigint, winner_method text, tiebreak jsonb)
          left join public.matches m on m.id = x.match_id and m.gameweek_id = p_gameweek_id
         where m.id is null
            or upper(m.status) is distinct from 'PENDING'
            or x.points_a is null or x.points_a < 0
            or x.points_b is null or x.points_b < 0
            or x.winner_id is null
            or x.winner_id not in (m.player_a_id, m.player_b_id)
            or x.winner_method is null
            or (x.points_a > x.points_b and x.winner_id is distinct from m.player_a_id)
            or (x.points_a > x.points_b and x.winner_method is distinct from 'FPL_POINTS')
            or (x.points_a > x.points_b and x.tiebreak is not null)
            or (x.points_b > x.points_a and x.winner_id is distinct from m.player_b_id)
            or (x.points_b > x.points_a and x.winner_method is distinct from 'FPL_POINTS')
            or (x.points_b > x.points_a and x.tiebreak is not null)
            or (x.points_a = x.points_b and x.winner_method not in ('VICE_CAPTAIN_POINTS', 'BENCH_POINTS'))
            or (x.points_a = x.points_b and x.tiebreak is null)
            or (x.points_a = x.points_b and case when jsonb_typeof(x.tiebreak) is distinct from 'object' then true else not (x.tiebreak ? 'winner' and x.tiebreak ? 'method' and x.tiebreak ? 'values') end)
            or (x.points_a = x.points_b and case when jsonb_typeof(x.tiebreak) is distinct from 'object' then true when jsonb_typeof(x.tiebreak->'winner') is distinct from 'number' then true else (x.tiebreak->>'winner')::numeric is distinct from x.winner_id::numeric end)
            or (x.points_a = x.points_b and case when jsonb_typeof(x.tiebreak) is distinct from 'object' then true when jsonb_typeof(x.tiebreak->'method') is distinct from 'string' then true else (x.tiebreak->>'method') is distinct from x.winner_method end)
            or (x.points_a = x.points_b and case when jsonb_typeof(x.tiebreak) is distinct from 'object' then true when jsonb_typeof(x.tiebreak->'values') is distinct from 'object' then true else not ((x.tiebreak->'values') ? m.player_a_id::text and (x.tiebreak->'values') ? m.player_b_id::text) end)
            or (x.points_a = x.points_b and case when jsonb_typeof(x.tiebreak) is distinct from 'object' then true when jsonb_typeof(x.tiebreak->'values') is distinct from 'object' then true when not ((x.tiebreak->'values') ? m.player_a_id::text and (x.tiebreak->'values') ? m.player_b_id::text) then true else case when jsonb_typeof((x.tiebreak->'values')->(m.player_a_id::text)) is distinct from 'number' then true when jsonb_typeof((x.tiebreak->'values')->(m.player_b_id::text)) is distinct from 'number' then true else case when (x.tiebreak->'values'->>m.player_a_id::text)::numeric is distinct from trunc((x.tiebreak->'values'->>m.player_a_id::text)::numeric) then true when (x.tiebreak->'values'->>m.player_b_id::text)::numeric is distinct from trunc((x.tiebreak->'values'->>m.player_b_id::text)::numeric) then true else false end end end)
            or (x.points_a = x.points_b and case when jsonb_typeof(x.tiebreak) is distinct from 'object' then true when jsonb_typeof(x.tiebreak->'values') is distinct from 'object' then true when not ((x.tiebreak->'values') ? m.player_a_id::text and (x.tiebreak->'values') ? m.player_b_id::text) then true when jsonb_typeof((x.tiebreak->'values')->(m.player_a_id::text)) is distinct from 'number' then true when jsonb_typeof((x.tiebreak->'values')->(m.player_b_id::text)) is distinct from 'number' then true when (x.tiebreak->'values'->>m.player_a_id::text)::numeric is distinct from trunc((x.tiebreak->'values'->>m.player_a_id::text)::numeric) then true when (x.tiebreak->'values'->>m.player_b_id::text)::numeric is distinct from trunc((x.tiebreak->'values'->>m.player_b_id::text)::numeric) then true else case when x.winner_id = m.player_a_id then (x.tiebreak->'values'->>m.player_a_id::text)::numeric <= (x.tiebreak->'values'->>m.player_b_id::text)::numeric else (x.tiebreak->'values'->>m.player_b_id::text)::numeric <= (x.tiebreak->'values'->>m.player_a_id::text)::numeric end end)
    ) then
        raise exception 'INVALID_MATCH_RESULT';
    end if;

    if (select count(distinct match_id) from jsonb_to_recordset(p_results) as x(match_id bigint)) <> v_result_count then
        raise exception 'DUPLICATE_MATCH_RESULT';
    end if;

    select count(distinct participant_id) into v_expected_player_count
      from (select player_a_id as participant_id from public.matches where gameweek_id = p_gameweek_id
            union select player_b_id from public.matches where gameweek_id = p_gameweek_id
            union select player_id from public.gameweek_byes where gameweek_id = p_gameweek_id) participants;

    select count(*) into v_player_count
      from jsonb_to_recordset(p_player_updates) as x(player_id bigint, status text, hearts integer, is_infected boolean, is_active boolean, "before" jsonb);

    if v_player_count <> v_expected_player_count then
        raise exception 'PLAYER_UPDATE_COUNT_MISMATCH';
    end if;

    if (select count(distinct player_id) from jsonb_to_recordset(p_player_updates) as x(player_id bigint)) <> v_player_count then
        raise exception 'DUPLICATE_PLAYER_UPDATE';
    end if;

    if exists (
        select 1
          from jsonb_to_recordset(p_player_updates) as x(player_id bigint, status text, hearts integer, is_infected boolean, is_active boolean, "before" jsonb)
          left join public.players p on p.id = x.player_id
         where p.id is null
            or x.status is null or x.status not in ('SAFE','NORMAL','DANGER')
            or x.hearts is null or x.hearts < 0 or x.hearts > 3
            or x.is_infected is null or x.is_active is null
            or x."before" is null
            or jsonb_typeof(x."before") is distinct from 'object'
            or not (x."before" ? 'status' and x."before" ? 'hearts' and x."before" ? 'is_infected' and x."before" ? 'is_active')
            or case when jsonb_typeof(x."before"->'status') is distinct from 'string' then true
                   when (x."before"->>'status') not in ('SAFE','NORMAL','DANGER','ELIMINATED') then true
                   when (x."before"->>'status') is distinct from p.status then true
                   else false end
            or case when jsonb_typeof(x."before"->'hearts') is distinct from 'number' then true
                   when (x."before"->>'hearts')::numeric is distinct from trunc((x."before"->>'hearts')::numeric) then true
                   when (x."before"->>'hearts')::numeric < 0 or (x."before"->>'hearts')::numeric > 3 then true
                   when (x."before"->>'hearts')::numeric is distinct from p.hearts::numeric then true
                   else false end
            or case when jsonb_typeof(x."before"->'is_infected') is distinct from 'boolean' then true
                   when (x."before"->>'is_infected')::boolean is distinct from p.is_infected then true
                   else false end
            or case when jsonb_typeof(x."before"->'is_active') is distinct from 'boolean' then true
                   when (x."before"->>'is_active')::boolean is distinct from p.is_active then true
                   else false end
    ) then
        raise exception 'PLAYER_STATE_CHANGED_SINCE_PREVIEW';
    end if;

    if exists (
        select 1 from (select player_a_id as participant_id from public.matches where gameweek_id = p_gameweek_id
                      union select player_b_id from public.matches where gameweek_id = p_gameweek_id
                      union select player_id from public.gameweek_byes where gameweek_id = p_gameweek_id) participants
        left join jsonb_to_recordset(p_player_updates) as x(player_id bigint) on x.player_id = participants.participant_id
        where x.player_id is null
    ) then
        raise exception 'PLAYER_UPDATE_COVERAGE_INCOMPLETE';
    end if;

    insert into public.player_gameweek_history (gameweek_id, player_id, status_before, status_after, hearts_before, hearts_after, infected_before, infected_after, active_before, active_after)
    select p_gameweek_id, x.player_id,
           upper(x."before"->>'status'),
           case when x.is_active then upper(x.status) else 'ELIMINATED' end,
           (x."before"->>'hearts')::integer,
           x.hearts,
           (x."before"->>'is_infected')::boolean,
           x.is_infected,
           (x."before"->>'is_active')::boolean,
           x.is_active
      from jsonb_to_recordset(p_player_updates) as x(player_id bigint, status text, hearts integer, is_infected boolean, is_active boolean, "before" jsonb);

    get diagnostics v_history_count = row_count;
    if v_history_count <> v_player_count then
        raise exception 'HISTORY_WRITE_INCOMPLETE';
    end if;

    update public.matches m
       set points_a = x.points_a, points_b = x.points_b, winner_id = x.winner_id,
           winner_method = x.winner_method, tiebreak = x.tiebreak, status = 'COMPLETED'
      from jsonb_to_recordset(p_results) as x(match_id bigint, points_a integer, points_b integer, winner_id bigint, winner_method text, tiebreak jsonb)
     where m.id = x.match_id and m.gameweek_id = p_gameweek_id;

    update public.players p
       set status = case when x.is_active then upper(x.status) else 'ELIMINATED' end,
           hearts = x.hearts, is_infected = x.is_infected, is_active = x.is_active
      from jsonb_to_recordset(p_player_updates) as x(player_id bigint, status text, hearts integer, is_infected boolean, is_active boolean, "before" jsonb)
     where p.id = x.player_id;

    update public.gameweeks set status = 'COMPLETED' where id = p_gameweek_id and upper(status) is not distinct from 'PENDING';
    if not found then raise exception 'GAMEWEEK_CONFIRMATION_RACE'; end if;

    -- Chapter II ends at GW14. Never create GW15: the tournament stops here.
    if v_gw_number < 14 then
        insert into public.gameweeks (gw_number, chapter, status)
        select v_gw_number + 1, v_gw_chapter, 'PENDING'
        where not exists (select 1 from public.gameweeks where gw_number = v_gw_number + 1)
        on conflict (gw_number) do nothing;

        if exists (select 1 from public.gameweeks where gw_number = v_gw_number + 1
                   and (upper(status) is distinct from 'PENDING'
                        or chapter is distinct from v_gw_chapter)) then
            raise exception 'NEXT_GAMEWEEK_INCONSISTENT';
        end if;
    end if;

    return jsonb_build_object('success', true, 'gameweek_id', p_gameweek_id, 'matches_completed', v_match_count, 'players_updated', v_player_count, 'history_rows_created', v_history_count);
end;
$$;

revoke all on function public.confirm_gameweek_results(bigint, jsonb, jsonb) from public;
revoke all on function public.confirm_gameweek_results(bigint, jsonb, jsonb) from anon;
revoke all on function public.confirm_gameweek_results(bigint, jsonb, jsonb) from authenticated;
