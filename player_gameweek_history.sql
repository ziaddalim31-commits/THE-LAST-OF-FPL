-- THE LAST OF FPL — atomic gameweek confirmation + survivor history
-- Apply manually in Supabase SQL Editor after reviewing this migration.
-- This file does not execute against Supabase by itself.

create table if not exists public.player_gameweek_history (
    id bigint generated by default as identity primary key,
    gameweek_id bigint not null references public.gameweeks(id) on delete restrict,
    player_id bigint not null references public.players(id) on delete restrict,
    status_before text not null,
    status_after text not null,
    hearts_before integer not null check (hearts_before between 0 and 3),
    hearts_after integer not null check (hearts_after between 0 and 3),
    infected_before boolean not null,
    infected_after boolean not null,
    active_before boolean not null,
    active_after boolean not null,
    created_at timestamptz not null default now(),
    constraint player_gameweek_history_status_before_check
        check (status_before in ('SAFE', 'NORMAL', 'DANGER', 'ELIMINATED')),
    constraint player_gameweek_history_status_after_check
        check (status_after in ('SAFE', 'NORMAL', 'DANGER', 'ELIMINATED')),
    constraint player_gameweek_history_unique_player_gw
        unique (gameweek_id, player_id)
);

create index if not exists idx_player_gameweek_history_player
    on public.player_gameweek_history (player_id, gameweek_id);

alter table public.player_gameweek_history enable row level security;

-- Preserve the official FPL/tie-break decision alongside the stored score.
alter table public.matches
    add column if not exists winner_method text,
    add column if not exists tiebreak jsonb;

-- One transaction confirms every match, updates every participant and writes
-- their before/after snapshot. Calling it twice cannot duplicate a gameweek.
create or replace function public.confirm_gameweek_results(
    p_gameweek_id bigint,
    p_results jsonb,
    p_player_updates jsonb
)
returns jsonb
language plpgsql
security definer
set search_path = public
as $$
declare
    v_gameweek_status text;
    v_match_count integer;
    v_result_count integer;
    v_player_count integer;
    v_expected_player_count integer;
    v_history_count integer;
begin
    if jsonb_typeof(p_results) <> 'array'
       or jsonb_typeof(p_player_updates) <> 'array' then
        raise exception 'INVALID_CONFIRMATION_PAYLOAD';
    end if;

    select upper(status)
      into v_gameweek_status
      from public.gameweeks
     where id = p_gameweek_id
     for update;

    if not found then
        raise exception 'GAMEWEEK_NOT_FOUND';
    end if;
    if v_gameweek_status <> 'PENDING' then
        raise exception 'GAMEWEEK_NOT_PENDING';
    end if;

    select count(*) into v_match_count
      from public.matches
     where gameweek_id = p_gameweek_id;

    select count(*) into v_result_count
      from jsonb_to_recordset(p_results) as x(
          match_id bigint,
          points_a integer,
          points_b integer,
          winner_id bigint,
          winner_method text,
          tiebreak jsonb
      );

    if v_match_count = 0 or v_result_count <> v_match_count then
        raise exception 'RESULT_MATCH_COUNT_MISMATCH';
    end if;

    if exists (
        select 1
          from jsonb_to_recordset(p_results) as x(
              match_id bigint,
              points_a integer,
              points_b integer,
              winner_id bigint,
              winner_method text,
              tiebreak jsonb
          )
          left join public.matches m
            on m.id = x.match_id
           and m.gameweek_id = p_gameweek_id
         where m.id is null
            or upper(m.status) <> 'PENDING'
            or x.points_a is null or x.points_a < 0
            or x.points_b is null or x.points_b < 0
            or x.winner_id is null
            or x.winner_id not in (m.player_a_id, m.player_b_id)
    ) then
        raise exception 'INVALID_MATCH_RESULT';
    end if;

    if (select count(distinct match_id)
          from jsonb_to_recordset(p_results) as x(match_id bigint)) <> v_result_count then
        raise exception 'DUPLICATE_MATCH_RESULT';
    end if;

    select count(distinct participant_id)
      into v_expected_player_count
      from (
          select player_a_id as participant_id from public.matches where gameweek_id = p_gameweek_id
          union
          select player_b_id as participant_id from public.matches where gameweek_id = p_gameweek_id
      ) participants;

    select count(*) into v_player_count
      from jsonb_to_recordset(p_player_updates) as x(
          player_id bigint,
          status text,
          hearts integer,
          is_infected boolean,
          is_active boolean,
          before jsonb
      );

    if v_player_count <> v_expected_player_count then
        raise exception 'PLAYER_UPDATE_COUNT_MISMATCH';
    end if;

    if (select count(distinct player_id)
          from jsonb_to_recordset(p_player_updates) as x(player_id bigint)) <> v_player_count then
        raise exception 'DUPLICATE_PLAYER_UPDATE';
    end if;

    if exists (
        select 1
          from jsonb_to_recordset(p_player_updates) as x(
              player_id bigint,
              status text,
              hearts integer,
              is_infected boolean,
              is_active boolean,
              before jsonb
          )
          left join public.players p on p.id = x.player_id
         where p.id is null
            or x.status is null
            or x.status not in ('SAFE', 'NORMAL', 'DANGER')
            or x.hearts is null or x.hearts < 0 or x.hearts > 3
            or x.is_infected is null or x.is_active is null
            or coalesce(x.before->>'status', '') <> p.status
            or coalesce((x.before->>'hearts')::integer, -1) <> p.hearts
            or coalesce((x.before->>'is_infected')::boolean, false) <> p.is_infected
            or coalesce((x.before->>'is_active')::boolean, false) <> p.is_active
    ) then
        raise exception 'PLAYER_STATE_CHANGED_SINCE_PREVIEW';
    end if;

    if exists (
        select 1
          from (
              select player_a_id as participant_id from public.matches where gameweek_id = p_gameweek_id
              union
              select player_b_id as participant_id from public.matches where gameweek_id = p_gameweek_id
          ) participants
          left join jsonb_to_recordset(p_player_updates) as x(
              player_id bigint,
              status text,
              hearts integer,
              is_infected boolean,
              is_active boolean,
              before jsonb
          ) on x.player_id = participants.participant_id
         where x.player_id is null
    ) then
        raise exception 'PLAYER_UPDATE_COVERAGE_INCOMPLETE';
    end if;

    insert into public.player_gameweek_history (
        gameweek_id, player_id,
        status_before, status_after,
        hearts_before, hearts_after,
        infected_before, infected_after,
        active_before, active_after
    )
    select
        p_gameweek_id,
        x.player_id,
        upper(x.before->>'status'),
        case when x.is_active then upper(x.status) else 'ELIMINATED' end,
        (x.before->>'hearts')::integer,
        x.hearts,
        (x.before->>'is_infected')::boolean,
        x.is_infected,
        (x.before->>'is_active')::boolean,
        x.is_active
    from jsonb_to_recordset(p_player_updates) as x(
        player_id bigint,
        status text,
        hearts integer,
        is_infected boolean,
        is_active boolean,
        before jsonb
    );

    get diagnostics v_history_count = row_count;
    if v_history_count <> v_player_count then
        raise exception 'HISTORY_WRITE_INCOMPLETE';
    end if;

    update public.matches m
       set points_a = x.points_a,
           points_b = x.points_b,
           winner_id = x.winner_id,
           winner_method = x.winner_method,
           tiebreak = x.tiebreak,
           status = 'COMPLETED'
      from jsonb_to_recordset(p_results) as x(
          match_id bigint,
          points_a integer,
          points_b integer,
          winner_id bigint,
          winner_method text,
          tiebreak jsonb
      )
     where m.id = x.match_id
       and m.gameweek_id = p_gameweek_id;

    update public.players p
       set status = case when x.is_active then upper(x.status) else 'ELIMINATED' end,
           hearts = x.hearts,
           is_infected = x.is_infected,
           is_active = x.is_active
      from jsonb_to_recordset(p_player_updates) as x(
          player_id bigint,
          status text,
          hearts integer,
          is_infected boolean,
          is_active boolean,
          before jsonb
      )
     where p.id = x.player_id;

    update public.gameweeks
       set status = 'COMPLETED'
     where id = p_gameweek_id
       and upper(status) = 'PENDING';

    if not found then
        raise exception 'GAMEWEEK_CONFIRMATION_RACE';
    end if;

    return jsonb_build_object(
        'success', true,
        'gameweek_id', p_gameweek_id,
        'matches_completed', v_match_count,
        'players_updated', v_player_count,
        'history_rows_created', v_history_count
    );
end;
$$;

revoke all on function public.confirm_gameweek_results(bigint, jsonb, jsonb) from public;
revoke all on function public.confirm_gameweek_results(bigint, jsonb, jsonb) from anon;
revoke all on function public.confirm_gameweek_results(bigint, jsonb, jsonb) from authenticated;
grant execute on function public.confirm_gameweek_results(bigint, jsonb, jsonb) to service_role;


-- Save a reviewed fixture schedule atomically after the admin approves it.
create or replace function public.save_gameweek_fixtures(
    p_gameweek_id bigint,
    p_fixtures jsonb,
    p_bye_player_id bigint default null
)
returns jsonb
language plpgsql
security definer
set search_path = public
as $$
declare
    v_gw_number integer;
    v_gw_status text;
    v_active_count integer;
    v_fixture_count integer;
    v_expected_fixtures integer;
    v_bye_count integer;
    v_covered_count integer;
    v_inserted_count integer;
begin
    if jsonb_typeof(p_fixtures) <> 'array' then
        raise exception 'INVALID_FIXTURE_PAYLOAD';
    end if;

    select gw_number, upper(status)
      into v_gw_number, v_gw_status
      from public.gameweeks
     where id = p_gameweek_id
     for update;

    if not found then
        raise exception 'GAMEWEEK_NOT_FOUND';
    end if;
    if v_gw_status <> 'PENDING' then
        raise exception 'GAMEWEEK_NOT_PENDING';
    end if;

    if exists (select 1 from public.matches where gameweek_id = p_gameweek_id)
       or exists (select 1 from public.gameweek_byes where gameweek_id = p_gameweek_id) then
        raise exception 'FIXTURES_ALREADY_EXIST';
    end if;

    select count(*) into v_active_count
      from public.players
     where is_active = true and hearts > 0;

    select count(*) into v_fixture_count
      from jsonb_to_recordset(p_fixtures) as x(
          player_a_id bigint,
          player_b_id bigint
      );

    v_expected_fixtures := floor(v_active_count / 2.0)::integer;
    v_bye_count := case when p_bye_player_id is null then 0 else 1 end;

    if v_active_count < 2 or v_fixture_count <> v_expected_fixtures
       or v_bye_count <> (v_active_count % 2) then
        raise exception 'FIXTURE_ROSTER_COVERAGE_INVALID';
    end if;

    if exists (
        select 1
          from jsonb_to_recordset(p_fixtures) as x(
              player_a_id bigint,
              player_b_id bigint
          )
          left join public.players a on a.id = x.player_a_id
          left join public.players b on b.id = x.player_b_id
         where x.player_a_id is null or x.player_b_id is null
            or x.player_a_id = x.player_b_id
            or a.id is null or b.id is null
            or a.is_active is distinct from true or b.is_active is distinct from true
            or a.hearts <= 0 or b.hearts <= 0
    ) then
        raise exception 'FIXTURE_PLAYER_INVALID';
    end if;

    if (select count(distinct player_id)
          from (
              select player_a_id as player_id
                from jsonb_to_recordset(p_fixtures) as x(player_a_id bigint, player_b_id bigint)
              union all
              select player_b_id as player_id
                from jsonb_to_recordset(p_fixtures) as x(player_a_id bigint, player_b_id bigint)
              union all
              select p_bye_player_id where p_bye_player_id is not null
          ) all_players) <> v_active_count then
        raise exception 'FIXTURE_ROSTER_COVERAGE_INVALID';
    end if;

    if exists (
        select 1
          from (
              select player_a_id as player_id
                from jsonb_to_recordset(p_fixtures) as x(player_a_id bigint, player_b_id bigint)
              union all
              select player_b_id as player_id
                from jsonb_to_recordset(p_fixtures) as x(player_a_id bigint, player_b_id bigint)
              union all
              select p_bye_player_id where p_bye_player_id is not null
          ) covered
          left join public.players p on p.id = covered.player_id
         where p.id is null or p.is_active is distinct from true or p.hearts <= 0
    ) then
        raise exception 'BYE_PLAYER_NOT_ACTIVE';
    end if;

    if exists (
        select 1
          from jsonb_to_recordset(p_fixtures) as x(
              player_a_id bigint,
              player_b_id bigint
          )
          join public.matches old_match
            on old_match.gameweek_id <> p_gameweek_id
           and (
                (old_match.player_a_id = x.player_a_id and old_match.player_b_id = x.player_b_id)
                or
                (old_match.player_a_id = x.player_b_id and old_match.player_b_id = x.player_a_id)
           )
          join public.gameweeks old_gw on old_gw.id = old_match.gameweek_id
         where old_gw.gw_number < v_gw_number
    ) then
        raise exception 'REMATCH_NOT_ALLOWED';
    end if;

    insert into public.matches (gameweek_id, player_a_id, player_b_id, status)
    select p_gameweek_id, x.player_a_id, x.player_b_id, 'PENDING'
      from jsonb_to_recordset(p_fixtures) as x(
          player_a_id bigint,
          player_b_id bigint
      );

    get diagnostics v_inserted_count = row_count;
    if v_inserted_count <> v_fixture_count then
        raise exception 'FIXTURE_INSERT_INCOMPLETE';
    end if;

    if p_bye_player_id is not null then
        insert into public.gameweek_byes (gameweek_id, player_id)
        values (p_gameweek_id, p_bye_player_id);
    end if;

    return jsonb_build_object(
        'success', true,
        'gameweek_id', p_gameweek_id,
        'matches_created', v_inserted_count,
        'bye_player_id', p_bye_player_id
    );
end;
$$;

revoke all on function public.save_gameweek_fixtures(bigint, jsonb, bigint) from public;
revoke all on function public.save_gameweek_fixtures(bigint, jsonb, bigint) from anon;
revoke all on function public.save_gameweek_fixtures(bigint, jsonb, bigint) from authenticated;
grant execute on function public.save_gameweek_fixtures(bigint, jsonb, bigint) to service_role;
